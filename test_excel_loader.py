def test_06_monsters():
    """Monster templates: expanded bestiary with correct base stats."""
    from game.data_loader import GameDataLoader
    loader = GameDataLoader()
    data = loader.load_all()
    monsters = data.get("MONSTER_TYPES", [])

    # Bestiary is generated by tools/gen_bestiary.py from RolePlayer's SRD
    # corpus: 40 species spanning CR 0.125 -> 20.
    check("bestiary has >= 30 species", len(monsters) >= 30,
          f"got {len(monsters)}")

    names = [m["name"] for m in monsters]
    check("monster names unique", len(names) == len(set(names)),
          f"{len(names) - len(set(names))} duplicates")

    # Every template must carry the depth gate produced by the generator.
    check("all have min_floor", all("min_floor" in m for m in monsters),
          f"missing on {sum(1 for m in monsters if 'min_floor' not in m)}")
    check("all have cr", all("cr" in m for m in monsters),
          f"missing on {sum(1 for m in monsters if 'cr' not in m)}")

    floors = [m["min_floor"] for m in monsters]
    check("min_floor starts at 1", min(floors) == 1, f"got {min(floors)}")
    check("depth gates spread out", len(set(floors)) >= 6,
          f"{len(set(floors))} distinct floors: {sorted(set(floors))}")

    # The four legacy species are still present (identity preserved) ...
    by_name = {m["name"].split(" ")[0]: m for m in monsters}
    for zh in ("哥布林", "兽人", "史莱姆", "骷髅兵"):
        check(f"legacy species {zh} still in the bestiary", zh in by_name,
              f"missing {zh}")

    # ... but they no longer carry hand-tuned outliers: every one of the 40
    # stat blocks must be exactly what curve(cr) produces.  The old overrides
    # (Skeleton 100/22/10, Orc 180/35/18) sat far above the curve for their
    # CR and walled off progression, so the sheet is now curve-consistent.
    def expect(cr, base, slope):
        return int(round(base + slope * cr))

    off_curve = []
    for m in monsters:
        cr = float(m.get("cr", 0))
        for key, base, slope in (("hp", 30, 55), ("attack", 8, 9),
                                 ("defense", 2, 4), ("exp", 12, 55),
                                 ("gold", 5, 16)):
            if int(m[key]) != expect(cr, base, slope):
                off_curve.append(f"{m['name']}:{key}={m[key]}")
    check("every stat block matches the CR curve", not off_curve,
          f"{len(off_curve)} off-curve: {off_curve[:6]}")

    # HP must rise monotonically with the depth gate (sanity of the curve).
    ordered = sorted(monsters, key=lambda m: m["min_floor"])
    first_tier = [m for m in ordered if m["min_floor"] == ordered[0]["min_floor"]]
    last_tier = [m for m in ordered if m["min_floor"] == ordered[-1]["min_floor"]]
    check("deepest tier is far tankier than first tier",
          min(m["hp"] for m in last_tier) > max(m["hp"] for m in first_tier) * 10,
          f"{min(m['hp'] for m in last_tier)} vs {max(m['hp'] for m in first_tier)}")


